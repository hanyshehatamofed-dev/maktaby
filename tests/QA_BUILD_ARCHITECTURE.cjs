const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const html = read('src/index.html');
const vite = read('vite.config.js');
const sw = read('src/sw.js');
const pkg = JSON.parse(read('package.json'));
const jsFiles = fs.readdirSync(path.join(root, 'src/js'));
const cssFiles = fs.readdirSync(path.join(root, 'src/css'));
assert.ok(jsFiles.every(x => !/\d{1,4}_\d{1,4}_\d{1,4}|\.[0-9a-f]{10,}\./i.test(x)), 'JS source names must not contain release/hash suffixes');
assert.ok(cssFiles.every(x => !/\d{1,4}_\d{1,4}_\d{1,4}|\.[0-9a-f]{10,}\./i.test(x)), 'CSS source names must not contain release/hash suffixes');
assert.match(html, /import\.meta\.glob\('\.\/js\/\*\.js'/);
assert.match(html, /import\.meta\.glob\('\.\/css\/\*\.css'/);
assert.match(html, /window\.MAKTABY_ASSET_URL\s*=\s*builtAsset/);
assert.ok(html.indexOf("loadScript('js/weekly-overview.js')") < html.indexOf("loadScript('js/renderer.js')"));
assert.ok(fs.existsSync(path.join(root, 'src/js/maktaby-task-archive.js')));
assert.ok(fs.existsSync(path.join(root, 'src/js/weekly-overview.js')));
assert.match(vite, /generatedServiceWorker/);
assert.match(vite, /minifiedClassicAssetUrls/);
assert.match(vite, /transformSync\(source, \{ loader: 'js'.*minify: true/);
assert.match(vite, /createHash\('sha256'\)/);
assert.match(vite, /__MAKTABY_BUILD_ID__/);
assert.match(vite, /publicDir:\s*resolve\(projectRoot, 'public'\)/);
assert.match(sw, /__MAKTABY_BUILD_ID__/);
assert.match(sw, /__MAKTABY_PRECACHE__/);
assert.ok(fs.existsSync(path.join(root, 'public/_headers')));
assert.ok(fs.existsSync(path.join(root, 'public/_redirects')));
assert.ok(fs.existsSync(path.join(root, 'public/manifest.json')));
assert.ok(fs.existsSync(path.join(root, 'tests')) && fs.existsSync(path.join(root, 'docs')));
assert.equal(pkg.version, '10.9.1');
console.log('MAKTABY build architecture QA: 15/15 passed');
