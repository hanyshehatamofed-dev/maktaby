const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const renderer=read('src/js/renderer.js');
const crm=read('src/js/maktaby-crm.js');
const achievements=read('src/js/maktaby-achievements.js');
const html=read('src/index.html');
const sw=read('src/sw.js');
const vite=read('vite.config.js');
assert.ok(!renderer.includes('V6.2 CRM PRO additive module'),'CRM implementation must not remain in core renderer');
assert.ok(!renderer.includes('V9.2.0 — Employee achievements'),'achievements implementation must not remain in core renderer');
assert.match(crm,/window\.crmConvertV6/);
assert.match(crm,/crm_leads/);
assert.match(crm,/crm_activities/);
assert.match(crm,/canManageOffice/);
assert.match(achievements,/window\.submitAchievementV920/);
assert.match(achievements,/window\.reviewAchievementV920/);
assert.match(achievements,/approval_requests/);
assert.match(html,/loadFeature\('crm','js\/maktaby-crm\.js','CRM'\)/);
assert.match(html,/loadFeature\('achievements','js\/maktaby-achievements\.js','employee achievements'\)/);
assert.match(html,/addEventListener\('click',async e=>/);
assert.ok(html.includes('crmButton.hidden=!(currentUser&&canManageOffice())'),'CRM visibility must use the renderer lexical session binding');
assert.ok(html.includes('if(!currentUser)return;'),'feature navigation must wait for an authenticated session');
assert.ok(html.includes('new MutationObserver(syncCrmNav).observe(loginScreen'),'CRM navigation visibility must refresh after restored sessions and logout');
assert.doesNotMatch(sw,/maktaby-(?:crm|achievements)/,'lazy business features must not be in the shell precache');
assert.ok(vite.includes('maktaby-(?:store|offline-sync|task-archive|weekly-overview)'),'core precache allowlist remains explicit');
assert.ok(fs.statSync(path.join(root,'src/js/renderer.js')).size<558807,'core renderer should shrink after extracting the two feature modules');
console.log('MAKTABY lazy feature extraction QA: 17/17 passed');
